"""Print the paper's discovery and separation tables and check every cell.

    uv run python evaluation/reproduce_tables.py

Reads the scores and discovery outputs under `RESULTS_PAPER` (see the README for
how they are regenerated) and checks every cell against the published value at
the precision it is printed.

DISCOVERY (tab:discovery). Per 10 s segment, the predicted labels (one per
claimed source, kept as a list) are compared with the active ground-truth labels:
    P = |pred ∩ true| / |pred|,  R = |pred ∩ true| / |true|,
    F1 = 2 |pred ∩ true| / (|pred| + |true|),  ΔK = | |pred| - |true| |,
averaged over the 1062 segments with at least one active source (P over the
segments with predictions). Predicting a label twice costs precision; a true
label can be matched once. Rows:
  * SEG, SEG (with res. embedding): the names recorded for the SEG queries
    (`SEG*_discovery.csv`). In a tree regenerated by `generate_estimates.py seg`
    the SEG embeddings are named with the stem classifier here instead, and
    checked against the recorded names.
  * Oracle Classifier: the names the same classifier gives the ground-truth
    sources, saved.
  * Multi-label Classifier, MusicFlamingo: their saved predictions.
Groups compare level-1 families (tracks mapped to their family). Instruments
compare individual tracks from `manifest_track.json`, with the vocal tracks
collapsed to `vocals`; a family word such as "drums" matches no track.

SEPARATION (tab:separation). Mean ± population sd of the stored per-item scores
(SAM-Audio Judge overall, mono SNR, MERT-MSE) over the population files. An
estimate more than 40 dB below its target is scored at -30 dB SNR. The per-item
scores can be recomputed from audio with `reproduce_separation_from_audio.py`.
"""

