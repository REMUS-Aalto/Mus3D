def same(x: float, ref: str | float | None) -> bool:
    """Does x print as the published cell?

    The paper's cells were rounded by hand, sometimes from a value already
    rounded to one more decimal (1.246 -> 1.25 -> 1.3), so any of the usual
    roundings to the published precision counts as a match.
    """
    from decimal import ROUND_HALF_UP, Decimal
    if ref is None:
        return True
    ref = f"{ref:.2f}" if isinstance(ref, float) else ref
    digits = len(ref.split(".")[1]) if "." in ref else 0
    q = lambda d: Decimal(1).scaleb(-d)
    d = Decimal(repr(x))
    candidates = {f"{x:.{digits}f}",
                  str(d.quantize(q(digits), ROUND_HALF_UP)),
                  str(d.quantize(q(digits + 1), ROUND_HALF_UP).quantize(q(digits), ROUND_HALF_UP))}
    return any(Decimal(c) == Decimal(ref) for c in candidates)


# ------------------------------------------------------------- discovery ----

def truth(manifest: str, track: bool) -> dict[str, set]:
    from data.moisesdb import LEAF_TO_GROUP
    t = defaultdict(set)
    for it in json.load(open(D / "ground_truth" / manifest))["items"]:
        if it["active"]:
            x = it["stem"]
            if track and LEAF_TO_GROUP.get(x) == "vocals":
                x = "vocals"
            t[f"{it['song_id']}/seg{int(it['segment_index']):03d}"].add(x)
    return t


def seg_predictions(level_dir: str, row: str, clf_level: str) -> dict[str, list]:
    base = D / "seg_embeddings" / level_dir / row
    if not base.is_dir():
        # The released results record the names; the embeddings are only in a
        # tree regenerated by `generate_estimates.py seg`.
        return saved_predictions(D / level_dir / f"{row}_discovery.csv")
    from classifiers.stem_classifier import StemClassifier
    clf = StemClassifier.load(str(CKPTS / "classifiers/stem_classifier_pcatrain.pkl"))
    out = {}
    for traj in sorted(base.glob("*/seg*/trajectory.csv")):
        steps = sorted(csv.DictReader(open(traj)), key=lambda s: int(s["step"]))
        names = []
        if steps:
            emb = np.stack([np.load(HERE / s["emb_path"]) for s in steps])
            names = list(clf.predict(emb, clf_level))
            if names != [s["named"] for s in steps]:
                raise SystemExit(f"{traj}: classifier names {names} differ from the recorded ones")
        out[f"{traj.parent.parent.name}/{traj.parent.name}"] = names
    return out


def saved_predictions(path: Path) -> dict[str, list]:
    out = {}
    for r in csv.DictReader(open(path)):
        col = "predicted_families" if "predicted_families" in r else "predicted_names"
        out[f"{r['song']}/seg{int(r['segment_index']):03d}"] = [x for x in r[col].split("|") if x]
    return out


def score(pred: dict[str, list], true: dict[str, set], track: bool):
    from data.moisesdb import LEAF_TO_GROUP
    Ps, Rs, Fs, dK = [], [], [], []
    for key, names in pred.items():
        t = true.get(key, set())
        p = ([("vocals" if LEAF_TO_GROUP.get(x) == "vocals" else x) for x in names] if track
             else [LEAF_TO_GROUP.get(x, x) for x in names])
        if not track:
            t = {LEAF_TO_GROUP.get(x, x) for x in t}
        dK.append(abs(len(p) - len(t)))
        if not p and not t:
            continue
        tp = len(set(p) & t)
        if p:
            Ps.append(tp / len(p))
        if t:
            Rs.append(tp / len(t))
        Fs.append(2 * tp / (len(p) + len(t)))
    return [(st.mean(v), st.stdev(v)) for v in (Fs, Ps, Rs, dK)], len(pred)


def discovery() -> int:
    bad = 0
    for level_dir, title, manifest, clf_level in [
            ("groups", "All Groups", "manifest.json", "stem"),
            ("instruments", "All Instr.", "manifest_track.json", "track")]:
        track = level_dir == "instruments"
        true = truth(manifest, track)
        preds = {
            "Oracle Classifier": saved_predictions(D / level_dir / "OracleClassifier_discovery.csv"),
            "Multi-label Classifier": saved_predictions(D / level_dir / "MultiLabelClassifier_discovery.csv"),
            "MusicFlamingo": saved_predictions(D / level_dir / "MusicFlamingo_discovery.csv"),
            "SEG": seg_predictions(level_dir, "SEG", clf_level),
            "SEG (with res. embedding)": seg_predictions(level_dir, "SEG-res-embedding", clf_level),
        }
        # every row is scored on the segments all rows cover that have active sources
        common = set.intersection(*(set(p) for k, p in preds.items() if k != "Oracle Classifier"))
        common &= set(true)      # drop the 3 segments with no active source
        print(f"\n{title}  ({len(common)} segments)")
        print(f"  {'':26s} {'F1':>13s} {'Precision':>13s} {'Recall':>13s} {'dK':>13s}   vs paper")
        for row in DISC_ORDER:
            p = {k: preds[row].get(k, []) for k in common}
            vals, _ = score(p, true, track)
            exp = DISC_EXPECTED[level_dir][row]
            ok = all(same(m, e) for (m, _), e in zip(vals, exp))
            bad += not ok
            print(f"  {row:26s} " + " ".join(f"{m:.3f}±{s:.3f}".rjust(13) for m, s in vals)
                  + ("   OK" if ok else f"   DIFF (paper {exp})"))
    return bad


