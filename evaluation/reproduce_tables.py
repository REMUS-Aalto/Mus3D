def per_item(block: str, metric: str, name: str, keys: set) -> list[float]:
    """The stored per-item scores of one row, restricted to the population.

    Two layouts are read: the released one (a benchmark results csv, whose SNR
    still needs the silence floor applied) and the one
    `reproduce_separation_from_audio.py` writes (song, segment, item, value).
    """
    path = HERE / "separation" / block / metric / f"{name}.csv"
    item = "track" if block == "all_instr" else "target"
    vals = {}
    for r in csv.DictReader(open(path)):
        if "item" in r:                      # written by the from-audio scorer
            k = (r["song"], int(r["segment"][3:]), r["item"])
            vals[k] = float(r[{"snr": "snr_mono", "judge": "JudgeOverall",
                               "mert": "MertMSE"}[metric]])
            continue
        k = (r["song"], int(float(r["segment_index"])), r[item])
        if k not in keys:
            continue
        if metric == "snr":
            v = float(r["snr_mono"])
            if "est_dbrms" in r and float(r["est_dbrms"]) < float(r["target_dbrms"]) - MARGIN:
                v = FLOOR
        else:
            v = float(r["JudgeOverall" if metric == "judge" else "MertMSE"])
        vals[k] = v
    if len(vals) != len(keys):
        raise SystemExit(f"{path}: {len(vals)} of {len(keys)} population items")
    return list(vals.values())


def separation() -> int:
    bad = 0
    for block, pop, item, title in [("groups", "groups_vdbgp.csv", "stem", "Groups: VDBGP"),
                                    ("all_instr", "all_instr.csv", "track", "All Instr.")]:
        keys = {(r["song"], int(r["segment"][3:]), r[item])
                for r in csv.DictReader(open(HERE / "populations" / pop))}
        print(f"\n{title}  ({len(keys)} items)")
        print(f"  {'':24s} {'Judge':>14s} {'SNR (dB)':>14s} {'MERT-MSE':>14s}   vs paper")
        for name, label in SEP_ROWS:
            if label not in SEP_EXPECTED[block]:
                continue
            got = []
            for metric in ("judge", "snr", "mert"):
                if name == "Ref_GroundTruth" and metric != "judge":
                    got += [None, None]
                    continue
                v = per_item(block, metric, name, keys)
                got += [st.mean(v), st.pstdev(v)]
            exp = SEP_EXPECTED[block][label]
            diff = [i for i, (g, e) in enumerate(zip(got, exp)) if g is not None and not same(g, e)]
            bad += bool(diff)
            cells = ["inf / 0" if got[i] is None else f"{got[i]:.3g}±{got[i + 1]:.2g}" for i in (0, 2, 4)]
            print(f"  {label:24s} " + " ".join(c.rjust(14) for c in cells)
                  + ("   OK" if not diff else "   DIFF " + ", ".join(
                      f"{['Judge', 'Judge sd', 'SNR', 'SNR sd', 'MERT', 'MERT sd'][i]} {got[i]:.3f} vs {exp[i]}"
                      for i in diff)))
    return bad


def main() -> None:
    print("=" * 30 + " DISCOVERY " + "=" * 30)
    bad = discovery()
    print("\n" + "=" * 30 + " SEPARATION " + "=" * 30)
    bad += separation()
    print("\n-> all published cells reproduced" if not bad else f"\n-> {bad} row(s) differ")


if __name__ == "__main__":
    main()
